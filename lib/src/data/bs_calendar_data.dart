/// Hard-coded Bikram Sambat calendar data.
///
/// Unlike the Gregorian calendar, the length of a Bikram Sambat month is not
/// given by a formula: it is derived from the solar sidereal position of the sun
/// and is published year by year. The only reliable way to implement BS date
/// arithmetic is therefore a lookup table of "days in each month of each year".
///
/// The table below covers **BS 1970 to BS 2199** (230 years), which maps to
/// **13 April 1913 to 15 April 2143** in the Gregorian
/// calendar. It is sourced from publicly available Nepali calendar data and has
/// been cross-checked against known Nepali New Year (1 Baishakh) dates — see
/// the `known date pairs` group in `test/date_converter_test.dart`.
library;

