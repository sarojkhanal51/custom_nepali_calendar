  /// Whether [year] is covered by [monthDays].
  static bool isSupportedYear(int year) => year >= minYear && year <= maxYear;

  /// Number of days in [month] (1-12) of the Bikram Sambat [year].
  ///
  /// Throws an [ArgumentError] if [year] is outside [minYear]..[maxYear] or if
  /// [month] is outside 1..12. Callers that need a user-facing error should
  /// validate with [isSupportedYear] first.
  static int daysInMonth(int year, int month) {
    final List<int>? months = monthDays[year];
    if (months == null) {
      throw ArgumentError.value(
        year,
        'year',
        'BS year is outside the supported range $minYear-$maxYear',
      );
    }
    if (month < 1 || month > monthsPerYear) {
      throw ArgumentError.value(
        month,
        'month',
        'BS month must be between 1 and 12',
      );
    }
    return months[month - 1];
  }

  /// Total number of days in the Bikram Sambat [year] (365, 366 or rarely 367).
  static int daysInYear(int year) {
    final List<int>? months = monthDays[year];
    if (months == null) {
      throw ArgumentError.value(
        year,
        'year',
        'BS year is outside the supported range $minYear-$maxYear',
      );
    }
    int total = 0;
    for (final int days in months) {
      total += days;
    }
    return total;
  }
